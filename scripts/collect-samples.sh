#!/usr/bin/env bash
# Copy the runs of a finished batch from outputs/ into samples/ and write samples/README.md.
#
#   scripts/collect-samples.sh <batch_id>
#
# Each run becomes samples/NN-<slug>/ with article.md, image.<ext> and metadata.json.
set -euo pipefail
cd "$(dirname "$0")/.."

batch_id="${1:?Usage: scripts/collect-samples.sh <batch_id>}"
summary="outputs/${batch_id}.json"
[[ -f "$summary" ]] || { echo "Missing $summary" >&2; exit 1; }
[[ "$(jq -r '.status' "$summary")" == "completed" ]] || { echo "Batch $batch_id has not finished yet" >&2; exit 1; }

find samples -mindepth 1 -maxdepth 1 -type d -name '[0-9][0-9]-*' -exec rm -rf {} +
jq 'del(.items[].article)' "$summary" > samples/batch-summary.json

rows=()
n=0
while IFS= read -r run_id; do
  n=$((n + 1))
  meta="outputs/${run_id}.json"
  if [[ -z "$run_id" || ! -f "$meta" ]]; then
    echo "skipping item $n: no output files" >&2
    continue
  fi
  slug=$(jq -r '.slug // "untitled"' "$meta" | cut -c1-60 | sed -E 's/-+$//')
  name=$(printf '%02d-%s' "$n" "$slug")
  dir="samples/$name"
  mkdir -p "$dir"
  jq 'del(.files)' "$meta" > "$dir/metadata.json"

  image=$(jq -r '.files.image // empty' "$meta")
  image_cell="-"
  if [[ -n "$image" && -f "$image" ]]; then
    ext="${image##*.}"
    cp "$image" "$dir/image.$ext"
    image_cell="<img src=\"$name/image.$ext\" width=\"180\">"
  fi
  if [[ -f "outputs/${run_id}.md" ]]; then
    sed "s|(${run_id}\.|(image.|" "outputs/${run_id}.md" > "$dir/article.md"
  fi

  rows+=("$(jq -r --arg name "$name" --arg image "$image_cell" '
    "| \($image) | [\(.title)](\($name)/article.md)<br><sub>\(.request.topic)</sub> | "
    + "\(.style)\(if .diversity.style_source == "auto" then " (auto)" else "" end) | "
    + "\(.word_count) | \(.status)\(if (.quality.revisions // 0) > 0 then ", \(.quality.revisions) revision" else "" end) | "
    + "\((.timings_ms.total / 1000) | floor) s | $\(.cost_usd) | "
    + "\(.diversity.angle), \(.diversity.hook), \(.diversity.audience) | "
    + "\(.diversity.visual.style); \(.diversity.visual.palette) |"' "$meta")")
done < <(jq -r '.items[].run_id // ""' "$summary")

{
  echo "# Sample outputs"
  echo
  jq -r '"Generated by one call to the Batch Runner (`\(.batch_id)`): \(.count) topics, concurrency \(.concurrency), "
    + "wall time \((.wall_time_ms / 1000) | floor) s. Per-run latency p50 \((.latency_ms.p50 / 1000) | floor) s, "
    + "p95 \((.latency_ms.p95 / 1000) | floor) s, max \((.latency_ms.max / 1000) | floor) s "
    + "(\(.runs_within_5_min)/\(.count) within 5 minutes). Total model cost $\(.cost_usd_total)."' "$summary"
  echo
  echo "The last two rows use the **same topic with style \`auto\`** to show the diversity logic: the second run"
  echo "sees the first in its history, so it must pick a different format, angle, hook, audience and visual direction."
  echo
  echo "| Image | Title and topic | Style | Words | Status | Time | Cost | Angle, hook, audience | Visual |"
  echo "|---|---|---|---|---|---|---|---|---|"
  printf '%s\n' "${rows[@]}"
  echo
  echo "Each folder holds \`article.md\` (Markdown with front matter), the image and \`metadata.json\`"
  echo "(plan, brief, quality checks per draft, every model call with latency and cost)."
  echo "[batch-summary.json](batch-summary.json) is the Batch Runner's own report."
} > samples/README.md

echo "wrote samples/README.md with ${#rows[@]} samples"
